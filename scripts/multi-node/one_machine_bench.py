#!/usr/bin/env python3
# Usage: one_machine_bench.py BENCH_RESC HARNESS_MACHINE DUT_MACHINE PLATFORM OUT_STEM
# Rewrites a two-machine Metalclaw bench script, and its I2C0 variants
# BENCH_i2c0_bus.resc and BENCH_i2c0_wires.resc, for one machine "bench"
# holding both chips as gen_rp2_chip_repl.py lays them out: the harness
# machine's peripherals become h_*, the DUT's d_*, and every delayed digital
# wire a plain zero-latency wire. Writes OUT_STEM.resc, OUT_STEM_i2c0_bus.resc
# and OUT_STEM_i2c0_wires.resc. I2C0 is still chosen with $i2c0_wiring; its
# byte-level bus keeps a latency, $i2c_latency_us, that must exceed two
# quanta. The SPI input delay, which only compensated the wire latency, is
# dropped.
import os, re, sys

bench, harness, dut, platform, out_stem = sys.argv[1:6]
prefix = {harness: 'h', dut: 'd'}
stem_name = os.path.basename(out_stem)
bench_stem = bench[:-len('.resc')]

# Two-machine paragraphs that no longer apply: the wire latency, jumpers,
# stand-ins and the SPI round trip.
STALE = r'latency|round trip|mach set|jumper|stand-in'


def paragraphs(lines, first_kept=True):
    result, block = [], []
    first = [first_kept]
    def flush():
        if block:
            if first[0] or not any(re.search(STALE, l) for l in block):
                result.extend(block)
            first[0] = False
            block.clear()
    for line in lines:
        if line.lstrip().startswith('#'):
            block.append(line)
        else:
            flush()
            result.append(line)
    flush()
    return result


def convert(lines, top):
    out = []
    current = None if top else harness_or_none
    for line in lines:
        s = line.rstrip('\n')
        if s.lstrip().startswith('#'):
            if re.search(r'load an image with `mach set', s):
                out.append("# The DUT's flash starts erased; load an image with `d_xipMemory LoadBinary`.")
                continue
            if re.search(r'^# `xipMemory LoadBinary`\.$', s):
                continue
            s = s.replace('metalclaw_carrier.resc', f'{stem_name}.resc').replace('metalclaw_fixture.resc', f'{stem_name}.resc')
            out.append(s)
            continue
        m = re.match(r'\s*mach (create|set) "([^"]+)"', s)
        if m:
            if m.group(1) == 'create' and current is None:
                out.append('mach create "bench"')
                out.append('machine LoadPlatformDescription $dual_platform')
            current = prefix[m.group(2)]
            continue
        if current is None:
            if re.match(r'\$(wire_latency_us|spi_input_delay_ns)\?=', s):
                continue
            if re.match(r'\$quantum\?=', s):
                # Both chips' cores share one machine's clock: a 10 us quantum,
                # one byte at 1 MHz, keeps a busy core from running far ahead
                # of a device another chip's core feeds.
                out.append('$quantum?="0.00001"')
                out.append('# The I2C0 bus latency; it must exceed two quanta.')
                out.append('$i2c_latency_us?=30')
                out.append(f'$dual_platform?=@{platform}')
                continue
            s = re.sub(r'^\$i2c0_wiring\?=@\S+_i2c0_(bus|wires)\.resc',
                       lambda m: f'$i2c0_wiring?=@{os.path.dirname(bench)}/{stem_name}_i2c0_{m.group(1)}.resc', s)
            out.append(s)
            continue
        p = current
        if re.match(r'\s*machine LoadPlatformDescription @', s): continue
        if re.match(r'\s*spi0 InputDelayNanoseconds', s): continue
        s = re.sub(r'emulation CreateDelayedDigitalWire ("[^"]+") (true|false) \$wire_latency_us', r'emulation CreateDigitalWire \1 \2', s)
        s = re.sub(r'emulation CreateDelayedI2CBus ("[^"]+") \$wire_latency_us', r'emulation CreateDelayedI2CBus \1 $i2c_latency_us', s)
        s = re.sub(r'^(\s*\S+ Connect) (gpio|debug_port|i2c0|i2c1) ', lambda m: f'{m.group(1)} {p}_{m.group(2)} ', s)
        s = re.sub(r'^(\s*)(rom|xipMemory|otp) ', lambda m: f'{m.group(1)}{p}_{m.group(2)} ', s)
        s = re.sub(r'^(\s*sysbus LoadBinary \S+ 0)\s*$', lambda m: f'{m.group(1)} sysbus.{p}_cluster.{p}_cpu0', s)
        s = re.sub(r'^(\s*host\.\S+ Register) usb ', lambda m: f'{m.group(1)} {p}_usb ', s)
        s = re.sub(r'"(adc_filter\d): (\S+) @ adc (\d)', lambda m: f'"{p}_{m.group(1)}: {m.group(2)} @ {p}_adc {m.group(3)}', s)
        s = re.sub(r'sysbus\.adc\.(adc_filter\d)', lambda m: f'sysbus.{p}_adc.{p}_{m.group(1)}', s)
        out.append(s)
    return out


harness_or_none = None
header = [f'# One-machine version of {os.path.basename(bench)}, generated by one_machine_bench.py:',
          '# machine "bench" holds the harness chip (h_*) and the DUT chip (d_*) of',
          f'# {os.path.basename(platform)}, joined by zero-latency wires.']
with open(f'{out_stem}.resc', 'w') as f:
    f.write('\n'.join(header + convert(paragraphs(open(bench).readlines()), True)) + '\n')
for variant in ('bus', 'wires'):
    source = f'{bench_stem}_i2c0_{variant}.resc'
    # An include file runs after the main script, with the harness selected.
    harness_or_none = 'h'
    lines = convert(paragraphs(open(source).readlines()), False)
    lines = [l.replace(f'{os.path.basename(bench)}', f'{stem_name}.resc') for l in lines]
    with open(f'{out_stem}_i2c0_{variant}.resc', 'w') as f:
        f.write('\n'.join(lines) + '\n')
