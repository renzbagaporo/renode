#!/usr/bin/env python3
# Usage: one_machine_bench.py BENCH_RESC I2C0_WIRES_RESC HARNESS_MACHINE DUT_MACHINE PLATFORM > one_machine.resc
# Rewrites a two-machine Metalclaw bench script for one machine "bench"
# holding both chips, as gen_rp2_chip_repl.py lays them out: the harness
# machine's peripherals become h_*, the DUT's d_*, every delayed wire a
# plain zero-latency wire, and I2C0 the plain pin-level wires of
# I2C0_WIRES_RESC. The SPI input delay, which only compensates the wire
# latency, is dropped.
import re, sys

bench, i2c0, harness, dut, platform = sys.argv[1:6]
prefix = {harness: 'h', dut: 'd'}
current = None
out = []

seen_code = False

def convert(lines):
    global current, seen_code
    for line in lines:
        s = line.rstrip('\n')
        if s.lstrip().startswith('#'):
            # The first comment block documents the variables; later comments
            # about the wire latency, jumpers or two machines no longer apply.
            if re.search(r'load an image with `mach set', s):
                out.append("# The DUT's flash starts erased; load an image with `d_xipMemory LoadBinary`.")
                continue
            if re.search(r'^# `xipMemory LoadBinary`\.$', s): continue
            s = s.replace('are connected below as $i2c0_wiring selects.', 'are plain pin-level wires below.')
        elif s.strip():
            seen_code = True
        m = re.match(r'\s*mach (create|set) "([^"]+)"', s)
        if m:
            if m.group(1) == 'create' and current is None:
                out.append('mach create "bench"')
                out.append(f'machine LoadPlatformDescription $dual_platform')
            current = prefix[m.group(2)]
            continue
        if current is None:
            if re.match(r'\$(wire_latency_us|spi_input_delay_ns|i2c0_wiring)\?=', s): continue
            if re.match(r'\$quantum\?=', s):
                # Both chips' cores share one machine's clock: a 10 us quantum,
                # one byte at 1 MHz, keeps a busy core from running far ahead
                # of a device another chip's core feeds.
                out.append('$quantum?="0.00001"')
                out.append(f'$dual_platform?=@{platform}')
                continue
            out.append(s)
            continue
        p = current
        if re.match(r'\s*machine LoadPlatformDescription @', s): continue
        if re.match(r'\s*spi0 InputDelayNanoseconds', s): continue
        if re.match(r'\s*include \$i2c0_wiring', s):
            convert([l for l in open(i2c0) if not l.startswith('#')])
            continue
        s = re.sub(r'emulation CreateDelayedDigitalWire ("[^"]+") (true|false) \$wire_latency_us', r'emulation CreateDigitalWire \1 \2', s)
        s = re.sub(r'^(\s*\S+ Connect) (gpio|debug_port) ', lambda m: f'{m.group(1)} {p}_{m.group(2)} ', s)
        s = re.sub(r'^(\s*)(rom|xipMemory|otp) ', lambda m: f'{m.group(1)}{p}_{m.group(2)} ', s)
        s = re.sub(r'^(\s*sysbus LoadBinary \S+ 0)\s*$', lambda m: f'{m.group(1)} sysbus.{p}_cluster.{p}_cpu0', s)
        s = re.sub(r'^(\s*host\.\S+ Register) usb ', lambda m: f'{m.group(1)} {p}_usb ', s)
        s = re.sub(r'"(adc_filter\d): (\S+) @ adc (\d)', lambda m: f'"{p}_{m.group(1)}: {m.group(2)} @ {p}_adc {m.group(3)}', s)
        s = re.sub(r'sysbus\.adc\.(adc_filter\d)', lambda m: f'sysbus.{p}_adc.{p}_{m.group(1)}', s)
        out.append(s)

def paragraphs(lines):
    # Drops whole comment paragraphs, after the first, that describe the wire
    # latency, jumpers, stand-ins, two machines or the I2C0 bus.
    result, block = [], []
    first = True
    def flush():
        nonlocal first
        if block:
            if first or not any(re.search(r'latency|round trip|mach set|jumper|stand-in|i2c0_bus|byte-level', l) for l in block):
                result.extend(block)
            first = False
            block.clear()
    for line in lines:
        if line.lstrip().startswith('#'): block.append(line)
        else:
            flush()
            result.append(line)
    flush()
    return result

convert(paragraphs(open(bench).readlines()))
print(f'# One-machine version of {bench.split("/")[-1]}, generated by one_machine_bench.py:')
print(f'# machine "bench" holds the harness chip (h_*) and the DUT chip (d_*) of')
print(f'# {platform.split("/")[-1]}, joined by zero-latency wires.')
print('\n'.join(out))
